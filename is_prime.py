import math


def is_prime(n: int) -> bool:
    if n <= 1:
        return False
    if n == 2:
        return True
    if n % 2 == 0:
        return False
    for i in range(3, math.isqrt(n) + 1, 2):
        if n % i == 0:
            return False
    return True


if __name__ == "__main__":
    for n in range(1, 21):
        print(f"{n}: {is_prime(n)}")
